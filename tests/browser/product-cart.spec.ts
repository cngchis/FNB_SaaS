import { test, expect } from '@playwright/test'
const product={code:'M00999',name:'Hàng hóa kiểm thử',category:'Retail SKU',productType:'Hàng hóa thường',menuType:'Đồ uống',price:35000,cost:15000,stock:24,baseUnit:'Lon',visible:true,extra:false,points:true,status:'Đang bán',attributes:JSON.stringify([{name:'Size',value:'M',price_delta_vnd:0},{name:'Size',value:'L',price_delta_vnd:5000}]),units:'[]'}

test.beforeEach(async ({page})=>{
 await page.addInitScript((row)=>{if(!localStorage.getItem('fnb-management:menu-items'))localStorage.setItem('fnb-management:menu-items',JSON.stringify([row]))},product)
})
test('product attribute prices persist and inventory details expand below the clicked row',async({page})=>{
 await page.goto('/management/menu-items')
 await page.getByRole('button',{name:`Sửa ${product.code}`,exact:true}).click()
 const dialog=page.getByRole('dialog')
 await expect(dialog.getByLabel('Giá cộng thêm thuộc tính (₫)')).toHaveCount(2)
 await dialog.getByLabel('Giá cộng thêm thuộc tính (₫)').nth(1).fill('7000')
 await dialog.screenshot({path:test.info().outputPath('attribute-editor.png')})
 await dialog.getByRole('button',{name:'Lưu món',exact:true}).click()
 await expect(dialog).toHaveCount(0)
 await page.locator('tr.record-expandable-row').click()
 await expect(page.locator('.product-detail-options')).toContainText('42.000')
 await page.goto('/management/inventory')
 const row=page.locator('tbody tr.record-expandable-row').filter({hasText:product.name})
 await row.click()
 const detail=page.locator('tr.record-detail-row')
 await expect(detail).toContainText('Size: L')
 await expect(detail).toContainText('42.000')
 await expect(detail).toContainText('15.000')
 await page.screenshot({path:test.info().outputPath('inventory-detail.png'),fullPage:true})
 await row.click()
 await expect(detail).toHaveCount(0)
 await row.getByRole('button',{name:`Thao tác ${product.name}`}).click()
 await expect(page.getByRole('dialog')).toBeVisible()
 await expect(detail).toHaveCount(0)
 const editor=page.getByRole('dialog',{name:'Cập nhật sản phẩm',exact:true})
 await expect(editor.getByLabel('Tên hàng',{exact:true})).toHaveValue(product.name)
 await editor.getByLabel('Giá bán (₫)',{exact:true}).fill('49000')
 await editor.getByLabel('Giá vốn (₫)',{exact:true}).fill('17000')
 await editor.getByLabel('Tồn kho',{exact:true}).fill('50')
 await editor.getByRole('textbox',{name:'Đơn vị cơ bản',exact:true}).fill('Chai')
 await editor.getByRole('button',{name:'Lưu món',exact:true}).click()
 await expect(editor).toHaveCount(0)
 await expect(row).toContainText(product.name)
 await row.click()
 await expect(page.locator('.menu-detail-field').filter({hasText:'Số lượng tồn kho'})).toContainText('50')
 await expect(page.locator('tr.record-detail-row')).toContainText('17.000')
 await page.goto('/management/menu-items')
 await page.getByRole('button',{name:`Sửa ${product.code}`,exact:true}).click()
 await expect(page.getByRole('dialog').getByLabel('Giá bán (₫)',{exact:true})).toHaveValue('49000')
 await expect(page.getByRole('dialog').getByRole('textbox',{name:'Đơn vị cơ bản',exact:true})).toHaveValue('Chai')
})
test('option price, percent/fixed discount popup, cancellation and payment display',async({page},info)=>{
 await page.goto('/pos')
 await page.locator('.pos-search input').fill(product.name)
 await page.getByRole('button',{name:`Thêm ${product.name} vào đơn hàng`,exact:true}).click()
 await page.getByRole('button',{name:/Size L/}).click()
 if(info.project.name==='mobile') await page.getByRole('button',{name:'Mở giỏ hàng',exact:true}).click()
 await expect(page.locator('.cart-item-bottom')).toContainText('40.000')
 await expect(page.locator('.cart-paid-field input')).toHaveCount(0)
 await expect(page.locator('.cart-paid-field')).toContainText('0')
 await page.getByLabel('Giảm giá đơn hàng',{exact:true}).click()
 let discount=page.getByRole('dialog',{name:'Giảm giá đơn hàng',exact:true})
 await discount.getByRole('button',{name:'%',exact:true}).click()
 await discount.getByLabel('Giá trị giảm giá',{exact:true}).fill('10')
 await expect(discount.locator('.shift-reconciliation')).toContainText('4.000')
 await discount.screenshot({path:test.info().outputPath('discount-dialog.png')})
 await discount.getByRole('button',{name:'Áp dụng',exact:true}).click()
 await expect(discount).toHaveCount(0)
 await expect(page.locator('.total-line')).toContainText('36.000')
 await page.getByLabel('Giảm giá đơn hàng',{exact:true}).click()
 discount=page.getByRole('dialog',{name:'Giảm giá đơn hàng',exact:true})
 await discount.getByRole('button',{name:'VND',exact:true}).click()
 await discount.getByLabel('Giá trị giảm giá',{exact:true}).fill('6000')
 await discount.getByRole('button',{name:'Hủy',exact:true}).click()
 await expect(page.locator('.total-line')).toContainText('36.000')
 await page.getByLabel('Giảm giá đơn hàng',{exact:true}).click()
 discount=page.getByRole('dialog',{name:'Giảm giá đơn hàng',exact:true})
 await discount.getByLabel('Giá trị giảm giá',{exact:true}).fill('6000')
 await discount.getByRole('button',{name:'Áp dụng',exact:true}).click()
 await expect(page.locator('.total-line')).toContainText('34.000')
 await page.getByRole('button',{name:'Tiền mặt',exact:true}).click()
 await expect(page.getByRole('dialog',{name:'Thanh toán tiền mặt'}).getByLabel('Khách thanh toán',{exact:true})).toBeVisible()
})

test('inventory create action reuses the product editor and saves a goods product', async ({ page }, info) => {
 await page.goto('/management/inventory')
 await page.getByRole('button', { name: 'Tạo mới sản phẩm', exact: true }).click()
 await expect(page).toHaveURL('/management/menu-items')
 const dialog = page.getByRole('dialog')
 await expect(dialog).toBeVisible()
 await dialog.getByLabel('Tên hàng', { exact: true }).fill(`Bia mới ${info.project.name}`)
 await dialog.getByLabel('Giá bán (₫)', { exact: true }).fill('22000')
 await dialog.getByLabel('Giá vốn (₫)', { exact: true }).fill('16000')
 await dialog.getByRole('textbox', { name: 'Đơn vị cơ bản', exact: true }).fill('Lon')
 await dialog.getByRole('button', { name: 'Lưu món', exact: true }).click()
 await expect(dialog).toHaveCount(0)
 await expect(page.locator('tbody tr.record-expandable-row').filter({ hasText: `Bia mới ${info.project.name}` })).toHaveCount(1)
 await page.getByRole('button', { name: 'Thêm món', exact: true }).click()
 await page.getByRole('dialog').getByRole('button', { name: 'Hủy', exact: true }).click()
 await expect(page.getByRole('dialog')).toHaveCount(0)
})
